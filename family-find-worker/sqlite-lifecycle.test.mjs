import test from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
import {createInvitation} from './invitations.mjs';
import {acceptInvitation} from './consent.mjs';
import {updatePosition} from './positions.mjs';
import {readViewerPosition} from './viewer.mjs';
import {revokeByDevice} from './revoke.mjs';
import {hashCapability} from './capabilities.mjs';
import worker from './worker.mjs';
test('Phase 1C: synthetic lifecycle on isolated in-memory SQLite',async()=>{
 const sql=new DatabaseSync(':memory:');
 try {
 sql.exec(readFileSync(new URL('./sql/staging-schema.sql',import.meta.url),'utf8'));
 const db={prepare(query){const stmt=sql.prepare(query);function bind(...args){return {first:async()=>stmt.get(...args)??null,run:async()=>({success:true,meta:stmt.run(...args)})};}return {...bind(),bind};}};
 const now=Math.floor(Date.now()/1000)-172800;
 const uid='synthetic-viewer';
 const pos={latitude:0,longitude:0,accuracy:10};
 const row=id=>sql.prepare('SELECT * FROM family_shares WHERE id=?').get(id);
 const invite=await createInvitation(db,uid,now);
 assert.equal(row(invite.id).invite_token_hash,await hashCapability(invite.token));
 assert.equal(row(invite.id).last_lat,null);
 assert.equal((await acceptInvitation(db,invite.token,false,now)).status,400);
 assert.equal((await readViewerPosition(db,invite.id,uid,now)).status,404);
 const consent=await acceptInvitation(db,invite.token,true,now+1);
 assert.equal(consent.id,invite.id);
 assert.equal(row(invite.id).device_token_hash,await hashCapability(consent.deviceToken));
 assert.equal((await acceptInvitation(db,invite.token,true,now+2)).status,410);
 assert.equal((await updatePosition(db,consent.deviceToken,{...pos,latitude:91},now+2)).status,400);
 assert.equal((await updatePosition(db,consent.deviceToken,pos,now+2)).status,200);
 assert.equal((await readViewerPosition(db,invite.id,'other-synthetic-viewer',now+3)).status,404);
 assert.equal((await readViewerPosition(db,invite.id,uid,now+3)).status,200);
 assert.equal((await revokeByDevice(db,invite.id,consent.deviceToken,now+4)).status,200);
 assert.equal(row(invite.id).last_lat,null);
 assert.equal(row(invite.id).device_token_hash,null);
 assert.equal((await updatePosition(db,consent.deviceToken,pos,now+20)).status,409);
 assert.equal((await readViewerPosition(db,invite.id,uid,now+20)).status,404);
 const expired=await createInvitation(db,uid,now);
 assert.equal((await acceptInvitation(db,expired.token,true,now+900)).status,410);
 const active=await createInvitation(db,uid,now);
 const accepted=await acceptInvitation(db,active.token,true,now+1);
 assert.equal((await updatePosition(db,accepted.deviceToken,pos,now+2)).status,200);
 assert.equal((await readViewerPosition(db,active.id,uid,accepted.expiresAt)).status,404);
 assert.equal((await updatePosition(db,accepted.deviceToken,pos,accepted.expiresAt)).status,409);
 const disabled=await worker.fetch(new Request('https://synthetic.invalid/v1/invitations',{method:'POST'}),{FAMILY_FIND_ENV:'staging',FAMILY_FIND_ENABLED:'false',DB:db});
 assert.equal(disabled.status,503);
 sql.exec(readFileSync(new URL('./sql/staging-cleanup.sql',import.meta.url),'utf8'));
 assert.equal(sql.prepare('SELECT COUNT(*) AS n FROM family_shares').get().n,0);
 } finally {sql.close();}
});
